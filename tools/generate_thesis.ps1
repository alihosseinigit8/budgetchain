function Add-Paragraph {
    param(
        [Parameter(Mandatory = $true)][AllowEmptyString()][string]$Text,
        [int]$Size = 13,
        [bool]$Bold = $false,
        [int]$Alignment = $wdAlignParagraphJustify,
        [object]$Style = $null,
        [int]$SpaceAfter = 7,
        [int]$SpaceBefore = 0
    )

    $position = [Math]::Max(0, $doc.Content.End - 1)
    $range = $doc.Range($position, $position)
    try {
        $step = 'نوشتن متن'
        $range.Text = $Text + [char]13
        $step = 'اعمال سبک'
        if ($null -ne $Style) { $range.Style = $Style }
        $step = 'فونت فارسی'
        $range.Font.Name = $persianFont
        $step = 'فونت لاتین'
        $range.Font.NameAscii = $englishFont
        $step = 'اندازهٔ فونت'
        $range.Font.Size = $Size
        $step = 'حالت ضخیم'
        $range.Font.Bold = [int]$Bold
        $step = 'تراز'
        $range.ParagraphFormat.Alignment = $Alignment
        $step = 'راست‌به‌چپ'
        $range.ParagraphFormat.ReadingOrder = $wdReadingOrderRtl
        $step = 'فاصلهٔ بعد'
        $range.ParagraphFormat.SpaceAfter = $SpaceAfter
        $step = 'فاصلهٔ قبل'
        $range.ParagraphFormat.SpaceBefore = $SpaceBefore
        $step = 'فاصلهٔ خط'
        $range.ParagraphFormat.LineSpacingRule = 0
    }
    catch {
        throw "خطا در درج پاراگراف «$Text» در مرحلهٔ ${step}: $($_.Exception.Message)"
    }
    return $range
}

function Add-Body {
    param([Parameter(Mandatory = $true)][string]$Text)
    $paragraphs = $Text.Trim() -split "(\r?\n){2,}"
    foreach ($paragraph in $paragraphs) {
        $clean = ($paragraph -replace "\r?\n", ' ').Trim()
        if ($clean) { Add-Paragraph -Text $clean | Out-Null }
    }
}

function Add-Heading {
    param(
        [Parameter(Mandatory = $true)][string]$Text,
        [int]$Level = 2
    )
    $style = if ($Level -eq 1) { 'Heading 1' } elseif ($Level -eq 2) { 'Heading 2' } else { 'Heading 3' }
    $size = if ($Level -eq 1) { 18 } elseif ($Level -eq 2) { 16 } else { 14 }
    Add-Paragraph -Text $Text -Size $size -Bold $true -Alignment $wdAlignParagraphRight -Style $style -SpaceAfter 10 -SpaceBefore 12 | Out-Null
}

function Add-PageBreak {
    $position = [Math]::Max(0, $doc.Content.End - 1)
    $range = $doc.Range($position, $position)
    $range.InsertBreak($wdPageBreak)
}

function Add-Table {
    param(
        [Parameter(Mandatory = $true)][string]$Caption,
        [Parameter(Mandatory = $true)][string[]]$Headers,
        [Parameter(Mandatory = $true)][object[]]$Rows
    )
    Add-Paragraph -Text $Caption -Size 12 -Bold $true -Alignment $wdAlignParagraphCenter -SpaceAfter 4 -SpaceBefore 8 | Out-Null
    $position = [Math]::Max(0, $doc.Content.End - 1)
    $range = $doc.Range($position, $position)
    $table = $doc.Tables.Add($range, $Rows.Count + 1, $Headers.Count)
    $table.Borders.Enable = 1
    $table.AllowAutoFit = $true
    for ($column = 1; $column -le $Headers.Count; $column++) {
        $cell = $table.Cell(1, $column)
        $cell.Range.Text = [string]$Headers[$column - 1]
        $cell.Range.Font.Name = $persianFont
        $cell.Range.Font.NameAscii = $englishFont
        $cell.Range.Font.Size = 11
        $cell.Range.Font.Bold = 1
        $cell.Range.ParagraphFormat.Alignment = $wdAlignParagraphCenter
        $cell.Range.ParagraphFormat.ReadingOrder = $wdReadingOrderRtl
    }
    $rowNumber = 2
    foreach ($row in $Rows) {
        for ($column = 1; $column -le $Headers.Count; $column++) {
            $cell = $table.Cell($rowNumber, $column)
            $cell.Range.Text = [string]$row[$column - 1]
            $cell.Range.Font.Name = $persianFont
            $cell.Range.Font.NameAscii = $englishFont
            $cell.Range.Font.Size = 11
            $cell.Range.ParagraphFormat.Alignment = $wdAlignParagraphRight
            $cell.Range.ParagraphFormat.ReadingOrder = $wdReadingOrderRtl
        }
        $rowNumber++
    }
    Add-Paragraph -Text '' -Size 4 -SpaceAfter 3 | Out-Null
}

function Add-FigurePlaceholder {
    param(

    $range = $doc.Range($position, $position)
    $table = $doc.Tables.Add($range, 1, 1)
    $table.Borders.Enable = 1
    $table.AllowAutoFit = $false
    $table.Rows.HeightRule = $wdRowHeightExactly
    $table.Rows.Height = 165
    $cell = $table.Cell(1, 1)
    $cell.VerticalAlignment = $wdCellAlignVerticalCenter
    $cell.Range.Text = "[محل درج شکل]" + [char]13 + $Guidance
    $cell.Range.Font.Name = $persianFont
    $cell.Range.Font.NameAscii = $englishFont
    $cell.Range.Font.Size = 13
    $cell.Range.Font.Bold = 0
    $cell.Range.ParagraphFormat.Alignment = $wdAlignParagraphCenter
    $cell.Range.ParagraphFormat.ReadingOrder = $wdReadingOrderRtl
    Add-Paragraph -Text $Caption -Size 12 -Bold $true -Alignment $wdAlignParagraphCenter -SpaceAfter 10 -SpaceBefore 3 | Out-Null
}

